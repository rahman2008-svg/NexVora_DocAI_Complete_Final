package com.nexvora.docai.feature.study

import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import java.io.File
import java.util.UUID

@Serializable data class StudyNote(val id: String, val title: String, val body: String, val updatedAt: Long)
@Serializable data class Flashcard(val front: String, val back: String)
@Serializable data class Deck(val id: String, val name: String, val cards: List<Flashcard> = emptyList())
@Serializable data class Mcq(val question: String, val options: List<String>, val correct: Int, val explanation: String = "")
@Serializable data class QuestionSet(val id: String, val name: String, val questions: List<Mcq> = emptyList())
@Serializable data class QuizAttempt(val setId: String, val setName: String, val correct: Int, val total: Int, val time: Long, val mode: String)
@Serializable data class StudyData(
    val notes: List<StudyNote> = emptyList(),
    val decks: List<Deck> = emptyList(),
    val sets: List<QuestionSet> = emptyList(),
    val attempts: List<QuizAttempt> = emptyList(),
)

data class ScoreResult(val correct: Int, val total: Int) {
    val percent: Int get() = if (total == 0) 0 else Math.round(correct * 100f / total)
}

object Scoring {
    /** [answers] maps question index to the chosen option index; unanswered questions count as wrong. */
    fun score(questions: List<Mcq>, answers: Map<Int, Int>): ScoreResult =
        ScoreResult(questions.indices.count { answers[it] == questions[it].correct }, questions.size)
}

fun Mcq.isValid(): Boolean = question.isNotBlank() && options.size >= 2 && options.all { it.isNotBlank() } && correct in options.indices

/** Notes, flashcards and question sets, saved locally as JSON (nothing is generated by AI). */
class StudyRepository(private val file: File, private val clock: () -> Long = { System.currentTimeMillis() }) {
    private val json = Json { ignoreUnknownKeys = true; encodeDefaults = true }
    private val _data = MutableStateFlow(load())
    val data: StateFlow<StudyData> = _data

    private fun load(): StudyData = try {
        if (file.exists()) json.decodeFromString(StudyData.serializer(), file.readText()) else StudyData()
    } catch (_: Exception) { StudyData() }

    @Synchronized
    private fun update(block: (StudyData) -> StudyData) {
        _data.value = block(_data.value)
        file.parentFile?.mkdirs()
        val tmp = File(file.path + ".tmp")
        tmp.writeText(json.encodeToString(StudyData.serializer(), _data.value))
        if (!tmp.renameTo(file)) { file.writeText(tmp.readText()); tmp.delete() }
    }

    fun newId(): String = UUID.randomUUID().toString()

    fun saveNote(id: String?, title: String, body: String): String {
        val noteId = id ?: newId()
        val note = StudyNote(noteId, title.trim().ifEmpty { "Untitled" }, body, clock())
        update { d -> d.copy(notes = listOf(note) + d.notes.filter { it.id != noteId }) }
        return noteId
    }
    fun deleteNote(id: String) = update { d -> d.copy(notes = d.notes.filter { it.id != id }) }

    fun createDeck(name: String): String { val id = newId(); update { d -> d.copy(decks = d.decks + Deck(id, name.trim())) }; return id }
    fun addCard(deckId: String, card: Flashcard) = update { d -> d.copy(decks = d.decks.map { if (it.id == deckId) it.copy(cards = it.cards + card) else it }) }
    fun deleteCard(deckId: String, index: Int) = update { d -> d.copy(decks = d.decks.map { if (it.id == deckId) it.copy(cards = it.cards.filterIndexed { i, _ -> i != index }) else it }) }
    fun deleteDeck(id: String) = update { d -> d.copy(decks = d.decks.filter { it.id != id }) }

    fun createSet(name: String): String { val id = newId(); update { d -> d.copy(sets = d.sets + QuestionSet(id, name.trim())) }; return id }
    fun addQuestion(setId: String, q: Mcq): Boolean {
        if (!q.isValid()) return false
        update { d -> d.copy(sets = d.sets.map { if (it.id == setId) it.copy(questions = it.questions + q) else it }) }
        return true
    }
    fun deleteQuestion(setId: String, index: Int) = update { d -> d.copy(sets = d.sets.map { if (it.id == setId) it.copy(questions = it.questions.filterIndexed { i, _ -> i != index }) else it }) }
    fun addAttempt(set: QuestionSet, result: ScoreResult, mode: String) =
        update { d -> d.copy(attempts = (listOf(QuizAttempt(set.id, set.name, result.correct, result.total, clock(), mode)) + d.attempts).take(200)) }

    fun createDeckWith(name: String, cards: List<Flashcard>): String { val id = newId(); update { d -> d.copy(decks = d.decks + Deck(id, name.trim(), cards)) }; return id }
    fun createSetWith(name: String, questions: List<Mcq>): String { val id = newId(); update { d -> d.copy(sets = d.sets + QuestionSet(id, name.trim(), questions.filter { it.isValid() })) }; return id }

    fun deleteSet(id: String) = update { d -> d.copy(sets = d.sets.filter { it.id != id }) }

    /** Additive merge used by backup restore: items whose id already exists are kept as they are. */
    fun merge(other: StudyData) = update { d ->
        d.copy(
            notes = d.notes + other.notes.filter { n -> d.notes.none { it.id == n.id } },
            decks = d.decks + other.decks.filter { n -> d.decks.none { it.id == n.id } },
            sets = d.sets + other.sets.filter { n -> d.sets.none { it.id == n.id } },
            attempts = (d.attempts + other.attempts.filter { n -> d.attempts.none { it == n } }).sortedByDescending { it.time }.take(200),
        )
    }

    fun exportJson(): String = json.encodeToString(StudyData.serializer(), _data.value)
    fun parse(text: String): StudyData? = try { json.decodeFromString(StudyData.serializer(), text) } catch (_: Exception) { null }
}

/** Parses JSON produced by a local model. Model output is untrusted: every item is validated, bad items are dropped. */
object AiJsonParser {
    private fun array(raw: String): kotlinx.serialization.json.JsonArray? {
        val a = raw.indexOf('[')
        val b = raw.lastIndexOf(']')
        if (a < 0 || b <= a) return null
        return try { kotlinx.serialization.json.Json.parseToJsonElement(raw.substring(a, b + 1)) as? kotlinx.serialization.json.JsonArray } catch (_: Exception) { null }
    }

    fun mcqs(raw: String): List<Mcq> = array(raw)?.mapNotNull { el ->
        runCatching {
            val o = el as kotlinx.serialization.json.JsonObject
            fun str(k: String) = (o[k] as? kotlinx.serialization.json.JsonPrimitive)?.content ?: ""
            val options = (o["options"] as kotlinx.serialization.json.JsonArray).map { (it as kotlinx.serialization.json.JsonPrimitive).content.trim() }
            val correct = (o["correct"] as kotlinx.serialization.json.JsonPrimitive).content.toInt()
            Mcq(str("question").trim(), options, correct, str("explanation").trim()).takeIf { it.isValid() }
        }.getOrNull()
    } ?: emptyList()

    fun flashcards(raw: String): List<Flashcard> = array(raw)?.mapNotNull { el ->
        runCatching {
            val o = el as kotlinx.serialization.json.JsonObject
            val f = (o["front"] as kotlinx.serialization.json.JsonPrimitive).content.trim()
            val b = (o["back"] as kotlinx.serialization.json.JsonPrimitive).content.trim()
            if (f.isNotEmpty() && b.isNotEmpty()) Flashcard(f, b) else null
        }.getOrNull()
    } ?: emptyList()
}
